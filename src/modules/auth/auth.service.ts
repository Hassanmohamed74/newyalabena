import { Injectable, UnauthorizedException, ConflictException, InternalServerErrorException, BadRequestException } from '@nestjs/common';
import { JwtService } from '@nestjs/jwt';
import { InjectRepository } from '@nestjs/typeorm';
import { Repository } from 'typeorm';
import { ConfigService } from '@nestjs/config';
import * as bcrypt from 'bcrypt';
import { authenticator } from 'otplib';
import * as QRCode from 'qrcode';
import { User } from '../../shared/entities/user.entity';
import { UserRole } from '../../shared/entities/user-role.entity';
import { Role } from '../../shared/entities/role.entity';
import { Student } from '../../shared/entities/student.entity';
import { ResetToken } from '../../shared/entities/reset-token.entity';
import { UserStatus } from '../../common/enums/user-status.enum';
import { LoginDto } from './dto/login.dto';
import { RegisterDto } from './dto/register.dto';
import { RefreshTokenDto } from './dto/refresh-token.dto';
import { TwoFactorLoginDto } from './dto/two-factor.dto';
import { EmailService } from '../email/email.service';

@Injectable()
export class AuthService {
  constructor(
    private jwtService: JwtService,
    @InjectRepository(User) private userRepo: Repository<User>,
    @InjectRepository(UserRole) private userRoleRepo: Repository<UserRole>,
    @InjectRepository(Role) private roleRepo: Repository<Role>,
    private emailService: EmailService,
    private config: ConfigService,
  ) {}

  async register(dto: RegisterDto) {
    const exists = await this.userRepo.findOne({
      where: [{ email: dto.email }, { phone: dto.phone }],
    });
    if (exists) throw new ConflictException('Email or phone already registered');

    const hash = await bcrypt.hash(dto.password, 12);

    // Resolve the default role BEFORE any write so a missing role can never
    // leave an orphaned user row behind.
    const studentRole = await this.roleRepo.findOne({ where: { slug: 'student' } });
    if (!studentRole) {
      throw new InternalServerErrorException(
        'Default student role not found in database. Please contact support.',
      );
    }

    // Atomic registration: the user, its (forced) student role and the
    // matching students row commit together. The admin /students list reads
    // the students table, so the profile row MUST exist for the account to
    // be visible there — a partial failure would recreate the historical
    // "registered but never listed" bug.
    const user = await this.userRepo.manager.transaction(async (em) => {
      const created = await em.getRepository(User).save(
        em.getRepository(User).create({
          email: dto.email,
          phone: dto.phone,
          password_hash: hash,
          first_name: dto.first_name,
          last_name: dto.last_name,
          branch_id: dto.branch_id,
          language: dto.language || 'ar',
          status: UserStatus.ACTIVE,
        }),
      );

      // Public registration can only ever be a student: RegisterDto carries
      // no role field and the ValidationPipe whitelist strips any extra key,
      // so this always assigns the hardcoded 'student' role.
      await em.getRepository(UserRole).save({
        user_id: created.id,
        role_id: studentRole.id,
        assigned_by: created.id,
      });

      // The students row mirrors the user (names live on users; this table
      // links via user_id only). student_number is generated by the
      // 'trg_students_number' DB trigger and status defaults to 'active'.
      await em.getRepository(Student).save(
        em.getRepository(Student).create({
          user_id: created.id,
          branch_id: dto.branch_id,
          enrollment_date: new Date(),
        } as Partial<Student>),
      );

      return created;
    });

    const roles = [studentRole.slug];
    const permissions = await this.getUserPermissions(user.id);
    return this.buildAuthResponse(user, roles, permissions);
  }

  async login(dto: LoginDto) {
    // Query builder (not findOne) so password_hash + two_factor_enabled are
    // selected for the 2FA gate below.
    const user = await this.userRepo
      .createQueryBuilder('user')
      .addSelect('user.password_hash')
      .where('user.email = :email', { email: dto.email })
      .getOne();
    if (!user) throw new UnauthorizedException('Invalid credentials');

    const valid = await bcrypt.compare(dto.password, user.password_hash);
    if (!valid) throw new UnauthorizedException('Invalid credentials');

    // 2FA gate (SRS 7.2): password OK, but a valid TOTP is still required.
    if (user.two_factor_enabled) {
      const temp_token = this.jwtService.sign(
        { sub: user.id, purpose: '2fa' },
        { expiresIn: '5m' },
      );
      return { requires_2fa: true, temp_token };
    }

    await this.userRepo.update(user.id, { last_login_at: new Date() });

    const roles = await this.getUserRoles(user.id);
    const permissions = await this.getUserPermissions(user.id);

    return this.buildAuthResponse(user, roles, permissions);
  }

  async refresh(dto: RefreshTokenDto) {
    try {
      const payload = this.jwtService.verify(dto.refresh_token, {
        secret: process.env.JWT_SECRET,
      });
      const user = await this.userRepo.findOne({ where: { id: payload.sub } });
      if (!user) throw new UnauthorizedException();

      const roles = await this.getUserRoles(user.id);
      const permissions = await this.getUserPermissions(user.id);
      return this.buildAuthResponse(user, roles, permissions);
    } catch {
      throw new UnauthorizedException('Invalid refresh token');
    }
  }

  /**
   * Request a password reset link to be sent to the user's email.
   * Generates a signed JWT token (purpose='reset') and stores it
   * in the resetTokens collection for server-side validation.
   */
  async requestPasswordReset(email: string) {
    const user = await this.userRepo.findOne({ where: { email } });
    if (!user) {
      // Intentionally silent: same response for existing and non-existing
      // emails prevents user enumeration.
      return;
    }

    // Generate a signed reset token (JWT with purpose='reset')
    const token = this.jwtService.sign(
      { sub: user.id, purpose: 'reset', email: user.email },
      { expiresIn: '1h' },
    );

    // Store the token with an expiry for invalidation (1 hour)
    const resetToken = this.userRepo.manager.create(ResetToken, {
      user: user,
      token,
      expires_at: new Date(Date.now() + 60 * 60 * 1000),
    });
    await this.userRepo.manager.save(resetToken);

    // Send reset email via email service with the token link
    const resetLink = `${this.config.get<string>('APP_URL')}/auth/reset?token=${token}`;
    await this.emailService.send({
      to: email,
      subject: 'Password Reset Link',
      html: `<p>Click <a href="${resetLink}">here</a> to reset your password.</p>`,
    });

    return { message: 'Reset link sent to your email' };
  }

  /**
   * Reset the user's password using the token from the email link.
   * Validates the token, hashes the new password, and logs the user in.
   */
  async resetPassword(token: string, newPassword: string) {
    let decoded: any;
    try {
      decoded = this.jwtService.verify(token, {
        secret: process.env.JWT_SECRET,
      });
    } catch {
      throw new UnauthorizedException('Invalid or expired reset token');
    }

    if (decoded.purpose !== 'reset' || !decoded.sub || !decoded.email) {
      throw new UnauthorizedException('Invalid reset token payload');
    }

    const user = await this.userRepo.findOne({
      where: { id: decoded.sub, email: decoded.email },
    });
    if (!user) {
      throw new UnauthorizedException('Invalid reset token');
    }

    // Verify the token hasn't expired or been used
    const storedToken = await this.userRepo
      .createQueryBuilder('reset_token')
      .where('reset_token.user_id = :userId', { userId: user.id })
      .andWhere('reset_token.token = :token', { token })
      .andWhere('reset_token.expires_at > :now', { now: new Date() })
      .getOne();

    if (!storedToken) {
      throw new UnauthorizedException('Invalid or expired reset token');
    }

    // Delete the token so it can't be reused
    await this.userRepo
      .createQueryBuilder()
      .delete()
      .where('id = :id', { id: storedToken.id })
      .execute();

    // Hash the new password and update the user
    const hash = await bcrypt.hash(newPassword, 12);
    await this.userRepo.update(user.id, { password_hash: hash });

    // Return fresh tokens so the user is logged in immediately
    const roles = await this.getUserRoles(user.id);
    const permissions = await this.getUserPermissions(user.id);
    return this.buildAuthResponse(user, roles, permissions);
  }

  private async getUserRoles(userId: string): Promise<string[]> {
    const userRoles = await this.userRoleRepo.find({
      where: { user_id: userId },
      relations: ['role'],
    });

    const slugs = userRoles
      .map((ur) => ur.role?.slug)
      .filter(Boolean) as string[];

    return slugs.length > 0 ? slugs : ['student'];
  }

  private async getUserPermissions(userId: string): Promise<string[]> {
    const userRoles = await this.userRoleRepo.find({
      where: { user_id: userId },
      relations: { role: { permissions: true } },
    });

    return [
      ...new Set(
        userRoles.flatMap((ur) =>
          (ur.role?.permissions ?? []).map((p) => `${p.module}:${p.action}`),
        ),
      ),
    ];
  }

  private buildAuthResponse(
    user: User,
    roles: string[] = ['student'],
    permissions: string[] = [],
  ) {
    const payload = { sub: user.id, email: user.email, roles };

    return {
      access_token: this.jwtService.sign(payload),
      refresh_token: this.jwtService.sign(payload, { expiresIn: '7d' }),
      user: {
        id: user.id,
        email: user.email,
        first_name: user.first_name,
        last_name: user.last_name,
        branch_id: user.branch_id,
        language: user.language,
        role: roles[0],
        roles,
        permissions,
      },
    };
  }

  // ─── Two-factor authentication (SRS 7.2) ─────────────────────

  /** Load a user (with the TOTP secret selected) for 2FA operations. */
  private async findUserFor2fa(userId: string): Promise<User | null> {
    return this.userRepo
      .createQueryBuilder('user')
      .addSelect('user.two_factor_secret')
      .where('user.id = :id', { id: userId })
      .getOne();
  }

  /**
   * Generate a pending TOTP secret, persist it (not yet active), and return
   * the otpauth URL + QR data URL for the authenticator app.
   */
  async setup2fa(userId: string) {
    const user = await this.userRepo.findOne({ where: { id: userId } });
    if (!user) throw new UnauthorizedException('User not found');
    if (user.two_factor_enabled) {
      throw new BadRequestException('Two-factor authentication is already enabled');
    }

    const secret = authenticator.generateSecret();
    await this.userRepo.update(userId, { two_factor_secret: secret });

    const otpauth_url = authenticator.keyuri(user.email, 'SpeakUp Academy', secret);
    const qr_code_data_url = await QRCode.toDataURL(otpauth_url);

    return { secret, otpauth_url, qr_code_data_url };
  }

  /** Confirm the pending secret with a valid TOTP code and switch 2FA on. */
  async enable2fa(userId: string, code: string) {
    const user = await this.findUserFor2fa(userId);
    if (!user) throw new UnauthorizedException('User not found');
    if (!user.two_factor_secret) {
      throw new BadRequestException('Run 2FA setup first');
    }
    if (!authenticator.check(code, user.two_factor_secret)) {
      throw new UnauthorizedException('Invalid authentication code');
    }

    await this.userRepo.update(userId, { two_factor_enabled: true });
    return { two_factor_enabled: true };
  }

  /** Verify a code against the active secret, then wipe it and switch 2FA off. */
  async disable2fa(userId: string, code: string) {
    const user = await this.findUserFor2fa(userId);
    if (!user) throw new UnauthorizedException('User not found');
    if (!user.two_factor_secret) {
      throw new BadRequestException('Two-factor authentication is not enabled');
    }
    if (!authenticator.check(code, user.two_factor_secret)) {
      throw new UnauthorizedException('Invalid authentication code');
    }

    await this.userRepo.update(userId, {
      two_factor_enabled: false,
      two_factor_secret: null as unknown as string,
    });
    return { two_factor_enabled: false };
  }

  /**
   * Complete a 2FA-gated login: validate the short-lived temp token (purpose
   * must be '2fa'), check the TOTP code, then issue the normal token pair.
   */
  async verify2fa(dto: TwoFactorLoginDto) {
    let payload: { sub?: string; purpose?: string };
    try {
      payload = this.jwtService.verify(dto.temp_token);
    } catch {
      throw new UnauthorizedException('Invalid or expired 2FA token');
    }
    if (payload.purpose !== '2fa' || !payload.sub) {
      throw new UnauthorizedException('Invalid or expired 2FA token');
    }

    const user = await this.findUserFor2fa(payload.sub);
    if (!user || !user.two_factor_enabled || !user.two_factor_secret) {
      throw new UnauthorizedException('Two-factor authentication is not enabled');
    }
    if (!authenticator.check(dto.code, user.two_factor_secret)) {
      throw new UnauthorizedException('Invalid authentication code');
    }

    await this.userRepo.update(user.id, { last_login_at: new Date() });

    const roles = await this.getUserRoles(user.id);
    const permissions = await this.getUserPermissions(user.id);
    return this.buildAuthResponse(user, roles, permissions);
  }
}
